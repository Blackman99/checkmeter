import type { Finding, Report } from '../core/analyse.js';
import { fmtPct, fmtTok, fmtWhen } from '../core/analyse.js';
import { tildify } from './render.js';

const LABEL: Record<string, string> = { OFF_LEDGER: 'OFF-LEDGER', FAST_METER: 'FAST METER', STUCK_RESET: 'STUCK RESET', PLAN_CHANGED: 'PLAN CHANGED', METER_DROP: 'METER DROP', LIMIT_HIT: 'LIMIT HIT', CACHE_TTL: 'CACHE TTL' };
const utc = (t: number) => new Date(t).toISOString().replace('.000', '');

/** Markdown you can paste into a support ticket. No prompts, no responses, no file contents beyond meter readings. */
export function renderEvidence(r: Report, opts: { demo?: boolean } = {}): string {
  const fs = r.findings.filter((f) => f.severity !== 'note' && LABEL[f.kind]);
  const o: string[] = [];
  const harnesses = [...new Set(fs.map((f) => f.harness))];
  const vendor = harnesses.length === 1 ? (harnesses[0] === 'codex' ? 'Codex' : 'Claude Code') : 'Codex / Claude Code';
  o.push(`# ${vendor} usage meter: readings that don't match my local usage`);
  o.push('');
  if (opts.demo) o.push('> **DEMO DATA.** Generated by `checkmeter --demo`; not a real account.\n');
  o.push(`Period: ${utc(r.since)} → ${utc(r.now)} (UTC). Generated by [checkmeter](https://github.com/Blackman99/checkmeter) ${r.version}, which only reads the session files the clients already write on this machine. Nothing here contains prompts, responses or code.`);
  const plans = r.harnesses.filter((h) => h.plans.length).map((h) => `${h.harness}: ${h.plans.join(' → ')}`);
  if (plans.length) o.push(`\nPlan as reported inside the meter readings: ${plans.join('; ')}.`);
  o.push('');
  if (!fs.length) { o.push('Every meter reading in this period matches the usage logged locally. Nothing to report.'); return o.join('\n') + '\n'; }
  o.push('## Summary');
  o.push('');
  o.push('| # | finding | meter | span (UTC) | meter moved | local usage in span |');
  o.push('|---|---|---|---|---|---|');
  fs.forEach((f, i) => {
    const span = f.from != null ? `${utc(f.from)} → ${utc(f.to ?? f.from)}` : '';
    const moved = f.delta != null ? `${f.delta >= 0 ? '+' : '−'}${Math.abs(f.delta).toFixed(1)} pts` : '';
    const local = f.tokens != null ? `${fmtTok(f.tokens)} weighted tokens${f.expected != null ? ` (≈ ${f.expected.toFixed(1)} pts at my usual rate)` : ''}` : '';
    o.push(`| ${i + 1} | ${LABEL[f.kind]} | ${f.harness} ${f.window ?? ''} | ${span} | ${moved} | ${local} |`);
  });
  o.push('');
  fs.forEach((f, i) => o.push(...section(f, i + 1)));
  o.push('## How these numbers were computed');
  o.push('');
  o.push('- **Meter readings** are copied verbatim from the client\'s own logs: Codex writes `rate_limits.primary` (5-hour) and `rate_limits.secondary` (weekly) with `used_percent`, `resets_at` and `plan_type` into every `token_count` event of `~/.codex/sessions/**/rollout-*.jsonl`. Claude Code readings come from its status line (`rate_limits.five_hour` / `seven_day`), recorded locally by `checkmeter record`.');
  o.push('- **Local usage** is the token counts the same files log per request, weighted by API price ratios (Codex: uncached input 1, cached input 0.1, output 8; Claude: input 1, cache read 0.1, 5-minute write 1.25, 1-hour write 2, output 5).');
  o.push('- **My usual rate** is the median, over days of steady work, of meter points per million weighted tokens. Findings compare the meter with itself, not with any published limit.');
  o.push('- Duplicate copies (subagent rollouts replay their parent\'s history; Claude Code streams a message more than once) are counted once.');
  return o.join('\n') + '\n';
}

function section(f: Finding, n: number): string[] {
  const o: string[] = [];
  o.push(`## ${n}. ${LABEL[f.kind]}: ${f.title}`);
  o.push('');
  for (const d of f.detail) o.push(`- ${d}`);
  if (f.readings.length) {
    o.push('');
    o.push('| reading | time (UTC) | local time | used | resets at (UTC) | plan | source |');
    o.push('|---|---|---|---|---|---|---|');
    f.readings.forEach((r, i) => {
      o.push(`| ${i === 0 ? 'before' : 'after'} | ${utc(r.t)} | ${fmtWhen(r.t)} | ${r.window} ${fmtPct(r.usedPercent)} | ${r.resetsAt ? utc(r.resetsAt) : '—'} | ${r.plan ?? '—'} | \`${tildify(r.file)}:${r.line}\` |`);
    });
    const a = f.readings[0];
    o.push('');
    o.push('Check it yourself:');
    o.push('');
    o.push('```sh');
    for (const r of f.readings) {
      if (r.harness === 'codex') o.push(`sed -n '${r.line}p' ${shq(tildify(r.file))} | jq -c '{timestamp, rate_limits: .payload.rate_limits}'`);
      else o.push(`sed -n '${r.line}p' ${shq(tildify(r.file))} | jq -c '{t, five_hour, seven_day}'`);
    }
    void a;
    o.push('```');
  }
  o.push('');
  return o;
}

const shq = (s: string) => (/^[\w~./:-]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`);
